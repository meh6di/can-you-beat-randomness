"""Item 9/10 - Turn results/*.csv into report-ready tables so no number is ever hand-copied.

Writes  results/summary.md           (all tables, GitHub-flavoured markdown)
        results/tex/<name>.tex       (one LaTeX table per CSV; \\input'ed by report.tex)
Missing CSVs are skipped. Usage: python make_report_tables.py
"""
import os

import pandas as pd

import config as C

R = C.RESULTS_DIR
# name: (caption, percent-formatted columns)
TABLES = {
    "stats_overall": ("ROI with bootstrap CI and efficient-market null (1 bet/match).", ["roi", "ci_lo", "ci_hi", "null_mean"]),
    "stats_per_league": ("Per-league ROI: note how wide the intervals are.", ["roi", "ci_lo", "ci_hi"]),
    "stats_paired": ("Paired bootstrap of total profit (A minus B, units).", []),
    "stats_power": ("Power analysis: what this sample can and cannot detect.", ["se_roi", "min_detectable_roi"]),
    "prob_scores": ("Proper scoring rules versus the market (lower is better).", []),
    "calibration": ("Calibration error (ECE) against its sampling-noise floor.", []),
    "clv_summary": ("Closing line value against Pinnacle's closing price.",
                    ["clv", "clv_lo", "clv_hi", "pct_clv_pos", "pct_beat_raw_close", "roi", "se_clv", "se_roi",
                     "pick_skill", "pick_skill_lo", "pick_skill_hi"]),
    "select_holdout": ("Strategy chosen on dev (CLV), evaluated once on the holdout.",
                       ["dev_clv", "hold_roi", "roi_lo", "roi_hi", "null_mean", "hold_clv", "clv_lo", "clv_hi", "hold_pick_skill"]),
    "market_bias_buckets": ("Blind betting by odds bucket (favourite-longshot bias).",
                            [c for p in ("Avg", "PS", "Max") for c in (f"roi_{p}", f"roi_{p}_lo", f"roi_{p}_hi")]
                            + ["implied_raw", "fair_prob", "win_freq", "win_freq_se"]),
    "market_bias_strategies": ("Simple blind strategies over all matches.", ["roi", "ci_lo", "ci_hi"]),
    "risk_drawdown": ("Flat-stake drawdown and final P&L distribution (units).", []),
    "risk_ruin": ("Probability of ruin by bankroll size (flat 1-unit stakes).", []),
    "risk_staking": ("Staking schemes from a 100-unit bankroll.", []),
}


def fmt(v, pct):
    if isinstance(v, (bool,)):
        return str(v)
    if pd.isna(v):
        return "-"
    if isinstance(v, (int,)) or (hasattr(v, "dtype") and "int" in str(v.dtype)):
        return str(int(v))
    if isinstance(v, float):
        return f"{100 * v:.2f}\\%" if pct else f"{v:.3f}"
    return str(v)


def esc(s):
    for a, b in (("\\%", "%"), ("_", "\\_"), ("%", "\\%"), ("&", "\\&"), ("#", "\\#")):
        s = s.replace(a, b)
    return s


def to_latex(df, caption, name, pct_cols):
    cols = list(df.columns)
    align = "".join("r" if pd.api.types.is_numeric_dtype(df[c]) else "l" for c in cols)
    lines = [r"\begin{table}[H]\centering\small", r"\resizebox{\textwidth}{!}{%",
             rf"\begin{{tabular}}{{{align}}}", r"\toprule",
             " & ".join(esc(c) for c in cols) + r" \\", r"\midrule"]
    for _, r in df.iterrows():
        lines.append(" & ".join(esc(fmt(r[c], c in pct_cols)).replace("\\\\%", "\\%") for c in cols) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}}", rf"\caption{{{esc(caption)}}}\label{{tab:{name}}}", r"\end{table}"]
    return "\n".join(lines)


def to_markdown(df, pct_cols):
    def f(v, c):
        s = fmt(v, c in pct_cols)
        return s.replace("\\%", "%")
    head = "| " + " | ".join(df.columns) + " |\n|" + "---|" * len(df.columns)
    body = "\n".join("| " + " | ".join(f(r[c], c) for c in df.columns) + " |" for _, r in df.iterrows())
    return head + "\n" + body


def main():
    os.makedirs(f"{R}/tex", exist_ok=True)
    md = ["# Results summary (auto-generated by make_report_tables.py)\n"]
    n = 0
    for name, (caption, pct) in TABLES.items():
        path = f"{R}/{name}.csv"
        if not os.path.exists(path):
            continue
        df = pd.read_csv(path)
        with open(f"{R}/tex/{name}.tex", "w") as f:
            f.write(to_latex(df, caption, name, pct))
        md.append(f"## {caption}\n\n{to_markdown(df, pct)}\n")
        n += 1
    with open(f"{R}/summary.md", "w") as f:
        f.write("\n".join(md))
    print(f"Wrote {n} tables to {R}/tex/ and {R}/summary.md")


if __name__ == "__main__":
    main()
